import type { Netlist } from "@/lib/schema/circuit";
import { DEVICE, forwardVolts, onOhms, valueOf } from "./devices";

// SPICE deck of the same circuit, so results can be cross-checked in ngspice.
// LEDs and diodes are written as the same piecewise-linear model the solver uses.
export function toSpice(netlist: Netlist, title = "Inkwire circuit"): string {
  const ground = netlist.components.find((c) => c.type === "ground")?.nodes[0];
  const battery = netlist.components.find((c) => c.type === "battery");
  const ref = ground ?? battery?.nodes[1];
  const net = (n: string) => (n === ref ? "0" : n.replace(/[^A-Za-z0-9_]/g, "_"));
  const lines = [`* ${title}`, "* Generated by Inkwire. Battery internal resistance and LED models match the in-app solver."];
  for (const c of netlist.components) {
    const [a, b, w] = c.nodes.map(net);
    const id = c.id.replace(/[^A-Za-z0-9_]/g, "_");
    switch (c.type) {
      case "battery":
        lines.push(`V${id} ${a} ${id}_int DC ${valueOf(c)}`, `R${id}_int ${id}_int ${b} ${DEVICE.batteryInternalOhms}`);
        break;
      case "resistor":
      case "lamp":
        lines.push(`R${id} ${a} ${b} ${valueOf(c)}`);
        break;
      case "potentiometer": {
        const p = c.position ?? 0.5;
        lines.push(`R${id}a ${a} ${b} ${Math.max(valueOf(c) * p, 1e-3)}`);
        if (w) lines.push(`R${id}b ${b} ${w} ${Math.max(valueOf(c) * (1 - p), 1e-3)}`);
        break;
      }
      case "switch":
      case "button":
        lines.push(`R${id} ${a} ${b} ${(c.closed ?? c.type === "switch") ? DEVICE.switchClosedOhms : 1e12}`);
        break;
      case "led":
      case "diode":
        {
          // Shockley model tuned so V = Vf at 20 mA before the series resistance:
          // N * Vt * ln(0.02 / Is) = Vf with Is = 1e-20.
          const n = forwardVolts(c) / (0.025852 * Math.log(0.02 / 1e-20));
          lines.push(`* ${id}: Vf ${forwardVolts(c)} V at 20 mA`, `D${id} ${a} ${b} D_${id}`, `.model D_${id} D(Is=1e-20 N=${n.toFixed(3)} Rs=${onOhms(c)})`);
        }
        break;
      case "capacitor":
        lines.push(`C${id} ${a} ${b} ${valueOf(c)}`);
        break;
      case "wire":
        lines.push(`R${id} ${a} ${b} 1e-6`);
        break;
      case "ground":
        break;
    }
  }
  lines.push(".op", ".end");
  return lines.join("\n") + "\n";
}
